#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Shorts Factory – מערכת אוטומציה חינמית ליצירת חומרי גלם ל-YouTube Shorts.

================================================================================
 תיעוד התקנה והפעלה (קראו לפני השימוש)
================================================================================

מה המערכת עושה (4 שלבים אוטומטיים):
  1. מזינה נושא כללי ומייצרת 5 רעיונות וכותרות קליטות בעזרת Groq (מודל Llama
     חינמי). אתם בוחרים את הרעיון המנצח (1-5).
  2. מייצרת תסריט קצרי וקצבי (עד 50 שניות), 3-4 סצנות ויזואליות עם פרומפטים
     מדויקים באנגלית לכלי וידאו חינמיים, וחבילת SEO (כותרת, תיאור, 15 תגיות
     והאשטאגים).
  3. ממירה את התסריט לקובץ קריינות MP3 עם gTTS (חינם, ללא מפתח API).
  4. שומרת הכל בתיקייה ייעודית עם קובץ Script_Metadata.txt מסודר.

--------------------------------------------------------------------------------
 1) דרישות מקדימות
--------------------------------------------------------------------------------
  • Python 3.9 ומעלה (מומלץ 3.10+).
  • חיבור אינטרנט (ל-Groq ול-gTTS).
  • חשבון Groq חינמי – https://console.groq.com/keys (אין צורך בכרטיס אשראי).

--------------------------------------------------------------------------------
 2) התקנת הספריות
--------------------------------------------------------------------------------
  פתחו טרמינל בשורש הפרויקט והריצו:

      # (מומלץ) סביבה וירטואלית
      python -m venv .venv
      source .venv/bin/activate          # לינוקס/macOS
      # .venv\\Scripts\\activate          # ווינדוס (PowerShell)

      pip install -r requirements.txt

  או להתקנה ידנית (כל הספריות חינמיות לחלוטין):

      pip install groq gtts requests

  אופציונלי – מנוע קריינות אופליין לגיבוי (כשאין אינטרנט):

      pip install pyttsx3
      # לינוקס דורש בנוסף: sudo apt install espeak-ng

--------------------------------------------------------------------------------
 3) הגדרת מפתח ה-API של Groq (חובה)
--------------------------------------------------------------------------------
  צרו מפתח ב-https://console.groq.com/keys והגדירו אותו כמשתנה סביבה:

      לינוקס/macOS (לסשן הנוכחי):   export GROQ_API_KEY="gsk_..."
      לינוקס/macOS (קבוע):          echo 'export GROQ_API_KEY="gsk_..."' >> ~/.bashrc && source ~/.bashrc
      ווינדוס CMD:                  set GROQ_API_KEY=gsk_...
      ווינדוס PowerShell:           $env:GROQ_API_KEY="gsk_..."

  חלופה נוחה: העתיקו את .env.example ל-.env וערכו אותו (נטען אוטומטית).

  משתני סביבה נוספים (כולם אופציונליים):
      GROQ_MODEL            – מודל Groq (ברירת מחדל: llama-3.3-70b-versatile)
      SHORTS_OUTPUT_DIR     – תיקיית הפלט (ברירת מחדל: output/)
      SHORTS_TTS_LANG       – שפת הקריינות (iw = עברית, en = אנגלית)
      SHORTS_IDEAS_COUNT    – מספר רעיונות (ברירת מחדל: 5)

--------------------------------------------------------------------------------
 4) הפעלה
--------------------------------------------------------------------------------
      python main.py                       # מצב אינטראקטיבי מלא
      python main.py --help                # כל האפשרויות
      python main.py -t "טיפים לחיסכון בכסף"  # עם נושא מוכן
      python main.py --check               # בדיקת תקינות המפתח והמודלים

--------------------------------------------------------------------------------
 5) פלט
--------------------------------------------------------------------------------
  output/idea-01-<כותרת-בלטינית>/
      ├── voiceover.mp3         קובץ הקריינות (MP3)
      ├── Script_Metadata.txt   תסריט + פרומפטים ויזואליים + SEO
      └── content.json          הנתונים הגולמיים מה-AI

================================================================================
"""

